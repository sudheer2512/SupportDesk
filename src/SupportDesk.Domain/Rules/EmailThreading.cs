using System.Text.RegularExpressions;

namespace SupportDesk.Domain.Rules;

/// <summary>
/// Pure helpers for inbound e-mail threading. Matching order used by the ingestion pipeline:
/// 1) In-Reply-To / References against stored Message-IDs, 2) reply token in a plus-address (support+t-XXXX@…),
/// 3) ticket number in the subject ([#1042]), 4) otherwise a new ticket.
/// </summary>
public static partial class EmailThreading
{
    public static string? NormalizeMessageId(string? id)
    {
        if (string.IsNullOrWhiteSpace(id)) return null;
        var t = id.Trim();
        if (t.StartsWith('<')) t = t[1..];
        if (t.EndsWith('>')) t = t[..^1];
        return t.Length == 0 ? null : t.Trim();
    }

    /// <summary>Splits a References / In-Reply-To header into normalised message ids (oldest first).</summary>
    public static IReadOnlyList<string> ParseReferences(string? header)
    {
        if (string.IsNullOrWhiteSpace(header)) return [];
        var ids = AngleIdRegex().Matches(header).Select(m => NormalizeMessageId(m.Value)).Where(x => x is not null).Select(x => x!).ToList();
        if (ids.Count == 0)
            ids = header.Split([' ', ',', '\t', '\r', '\n'], StringSplitOptions.RemoveEmptyEntries)
                .Select(NormalizeMessageId).Where(x => x is not null).Select(x => x!).ToList();
        return ids.Distinct(StringComparer.Ordinal).ToList();
    }

    /// <summary>Generates an RFC 5322 Message-ID for an outbound message.</summary>
    public static string NewMessageId(Guid messageId, string domain) => $"{messageId:N}@{domain}";

    /// <summary>Extracts the ticket number from a subject tag such as "[#1042]" or "[SD-1042]".</summary>
    public static long? ExtractTicketNumber(string? subject, string? prefix = null)
    {
        if (string.IsNullOrWhiteSpace(subject)) return null;
        var m = TicketTagRegex().Match(subject);
        if (m.Success && (prefix is null || string.IsNullOrEmpty(m.Groups["prefix"].Value) ||
                          m.Groups["prefix"].Value.TrimEnd('-').Equals(prefix.TrimEnd('-'), StringComparison.OrdinalIgnoreCase)))
            return long.Parse(m.Groups["num"].Value);
        return null;
    }

    public static string TagSubject(string subject, string tag)
    {
        var clean = StripTicketTag(subject);
        return $"{clean} [{tag}]".Trim();
    }

    public static string StripTicketTag(string subject) => TicketTagRegex().Replace(subject, "").Trim();

    /// <summary>Removes reply/forward prefixes (Re:, RE:, Fwd:, FW:, AW:, WG:, SV:, Antw:) repeatedly.</summary>
    public static string StripReplyPrefixes(string? subject)
    {
        if (string.IsNullOrWhiteSpace(subject)) return "";
        var s = subject.Trim();
        string prev;
        do
        {
            prev = s;
            s = ReplyPrefixRegex().Replace(s, "").Trim();
        } while (s != prev);
        return s;
    }

    /// <summary>Reply token from a plus-address: support+t-ab12cd34@example.com → ab12cd34.</summary>
    public static string? ExtractReplyToken(IEnumerable<string> recipientAddresses)
    {
        foreach (var addr in recipientAddresses)
        {
            var m = ReplyTokenRegex().Match(addr);
            if (m.Success) return m.Groups["token"].Value.ToLowerInvariant();
        }
        return null;
    }

    public static string WithReplyToken(string address, string token)
    {
        var at = address.IndexOf('@');
        if (at <= 0) return address;
        var local = address[..at];
        var plus = local.IndexOf('+');
        if (plus >= 0) local = local[..plus];
        return $"{local}+t-{token}{address[at..]}";
    }

    /// <summary>True for out-of-office, bounce and bulk mail (RFC 3834 Auto-Submitted, Precedence, vendor headers).</summary>
    public static bool IsAutoGenerated(IReadOnlyDictionary<string, string> headers, string? fromAddress)
    {
        string? H(string name) => headers.TryGetValue(name, out var v) ? v : headers
            .FirstOrDefault(kv => kv.Key.Equals(name, StringComparison.OrdinalIgnoreCase)).Value;

        var autoSubmitted = H("Auto-Submitted");
        if (!string.IsNullOrEmpty(autoSubmitted) && !autoSubmitted.Equals("no", StringComparison.OrdinalIgnoreCase)) return true;
        var precedence = H("Precedence");
        if (precedence is not null && (precedence.Contains("bulk", StringComparison.OrdinalIgnoreCase) ||
                                       precedence.Contains("junk", StringComparison.OrdinalIgnoreCase) ||
                                       precedence.Contains("auto_reply", StringComparison.OrdinalIgnoreCase))) return true;
        if (!string.IsNullOrEmpty(H("X-Autoreply")) || !string.IsNullOrEmpty(H("X-Autorespond"))) return true;
        var suppress = H("X-Auto-Response-Suppress");
        if (suppress is not null && suppress.Contains("All", StringComparison.OrdinalIgnoreCase)) return true;
        if (fromAddress is not null && MailerDaemonRegex().IsMatch(fromAddress)) return true;
        return false;
    }

    /// <summary>
    /// Separates the new content of a plain-text reply from the quoted history
    /// ("On … wrote:", "-----Original Message-----", "From: … Sent:", lines starting with '>').
    /// </summary>
    public static (string Reply, string? Quoted) SplitQuotedText(string? text)
    {
        if (string.IsNullOrEmpty(text)) return ("", null);
        var lines = text.Replace("\r\n", "\n").Split('\n');
        for (var i = 0; i < lines.Length; i++)
        {
            var line = lines[i].Trim();
            var isMarker = OnWroteRegex().IsMatch(line) || line.StartsWith("-----Original Message-----", StringComparison.OrdinalIgnoreCase)
                || line.StartsWith("________________________________", StringComparison.Ordinal)
                || (line.StartsWith("From:", StringComparison.OrdinalIgnoreCase) && i + 1 < lines.Length &&
                    lines.Skip(i + 1).Take(3).Any(l => l.TrimStart().StartsWith("Sent:", StringComparison.OrdinalIgnoreCase) ||
                                                       l.TrimStart().StartsWith("Date:", StringComparison.OrdinalIgnoreCase)));
            var quoteBlock = line.StartsWith('>') && lines.Skip(i).All(l => l.TrimStart().StartsWith('>') || string.IsNullOrWhiteSpace(l));
            if (isMarker || quoteBlock)
            {
                var reply = string.Join('\n', lines.Take(i)).TrimEnd();
                var quoted = string.Join('\n', lines.Skip(i)).Trim();
                return (reply.Length == 0 ? text.Trim() : reply, quoted.Length == 0 ? null : quoted);
            }
        }
        return (text.Trim(), null);
    }

    [GeneratedRegex(@"<[^<>\s]+>")]
    private static partial Regex AngleIdRegex();

    [GeneratedRegex(@"\[(?:Ticket\s*)?(?<prefix>[A-Za-z]{1,8}-)?#?(?<num>\d{1,12})\]", RegexOptions.IgnoreCase)]
    private static partial Regex TicketTagRegex();

    [GeneratedRegex(@"^(re|fw|fwd|aw|wg|sv|antw|vs|ref|tr)\s*(\[\d+\])?\s*:\s*", RegexOptions.IgnoreCase)]
    private static partial Regex ReplyPrefixRegex();

    [GeneratedRegex(@"\+t-(?<token>[a-z0-9]{6,32})@", RegexOptions.IgnoreCase)]
    private static partial Regex ReplyTokenRegex();

    [GeneratedRegex(@"^(mailer-daemon|postmaster|no-?reply)@", RegexOptions.IgnoreCase)]
    private static partial Regex MailerDaemonRegex();

    [GeneratedRegex(@"^On .{4,200} wrote:$", RegexOptions.IgnoreCase)]
    private static partial Regex OnWroteRegex();
}
