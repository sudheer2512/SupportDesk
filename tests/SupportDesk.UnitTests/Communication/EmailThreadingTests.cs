using System.Security.Cryptography;
using System.Text;
using SupportDesk.Application.Communication;
using SupportDesk.Domain.Rules;
using SupportDesk.Integrations.Email;

namespace SupportDesk.UnitTests.Communication;

public sealed class EmailThreadingTests
{
    private static byte[] Raw(string headersAndBody) => Encoding.UTF8.GetBytes(headersAndBody.Replace("\n", "\r\n"));

    [Fact]
    public void Mime_parser_extracts_threading_headers()
    {
        var email = new MimeCodec().Parse(Raw("""
            From: "Ramesh Kumar" <Ramesh@ABCRetail.demo>
            To: support+t-1042xabc@wings.demo
            Cc: lata@abcretail.demo
            Subject: RE: Invoice mismatch [#1042]
            Message-ID: <reply-2@mail.abcretail.demo>
            In-Reply-To: <out-1@support.wings.demo>
            References: <root-0@mail.abcretail.demo>
             <out-1@support.wings.demo>
            Auto-Submitted: no
            Content-Type: text/plain; charset=utf-8

            Thanks, it works now.
            """));

        Assert.Equal("reply-2@mail.abcretail.demo", email.MessageId);
        Assert.Equal("out-1@support.wings.demo", email.InReplyTo);
        Assert.Equal(["root-0@mail.abcretail.demo", "out-1@support.wings.demo"], email.References);
        Assert.Equal("Ramesh Kumar", email.FromName);
        Assert.Equal("Ramesh@ABCRetail.demo", email.FromAddress);
        Assert.Contains("lata@abcretail.demo", email.Cc);
        Assert.False(EmailThreading.IsAutoGenerated(email.Headers, TextNormalization.NormalizeEmail(email.FromAddress)));
        Assert.Equal(1042, EmailThreading.ExtractTicketNumber(email.Subject));
    }

    [Fact]
    public void Composed_reply_round_trips_threading_headers_reply_to_and_inline_images()
    {
        var codec = new MimeCodec();
        var raw = codec.Compose(new OutboundEmail("support@wings.demo", "Wings Support", ["anita@sunrisepharma.demo"], [], [], "support+t-1193x0123456789@wings.demo",
            "Re: Batch report [#1193]", "<p>See <img src=\"cid:shot1\"></p>", "See the screenshot", "abc123@support.wings.demo", "orig@mail.sunrisepharma.demo",
            ["orig@mail.sunrisepharma.demo"], [new EmailAttachment("shot.png", "image/png", [0x89, 0x50, 0x4E, 0x47], "shot1", Inline: true)],
            new Dictionary<string, string> { ["X-SupportDesk-Ticket"] = "1193", ["Subject"] = "ignored", ["X-Bad\r\nInjected"] = "x" }));
        var parsed = codec.Parse(raw);

        Assert.Equal("abc123@support.wings.demo", parsed.MessageId);
        Assert.Equal("orig@mail.sunrisepharma.demo", parsed.InReplyTo);
        Assert.Equal(["orig@mail.sunrisepharma.demo"], parsed.References);
        Assert.Equal("Re: Batch report [#1193]", parsed.Subject);
        Assert.Equal("1193", parsed.Headers["X-SupportDesk-Ticket"]);
        Assert.DoesNotContain(parsed.Headers.Keys, k => k.Contains("Injected"));
        Assert.Contains("support+t-1193x0123456789@wings.demo", Encoding.UTF8.GetString(raw));
        var inline = Assert.Single(parsed.Attachments);
        Assert.Equal("shot1", inline.ContentId);
        Assert.True(inline.Inline);
    }

    [Fact]
    public void Reply_tokens_are_signed_and_survive_plus_addressing()
    {
        var key = RandomNumberGenerator.GetBytes(32);
        var token = ReplyTokens.Create(key, 1042);
        var address = EmailThreading.WithReplyToken("support@wings.demo", token);

        Assert.Matches(@"^support\+t-[a-z0-9]+@wings\.demo$", address);
        var extracted = EmailThreading.ExtractReplyToken(["someone@else.demo", address]);
        Assert.Equal(1042, ReplyTokens.Parse(key, extracted));
        // A guessed or tampered token is rejected, as is a token signed with another tenant's key.
        Assert.Null(ReplyTokens.Parse(key, "1043" + token[token.IndexOf('x')..]));
        Assert.Null(ReplyTokens.Parse(RandomNumberGenerator.GetBytes(32), token));
        Assert.Null(ReplyTokens.Parse(key, "garbage"));
    }

    [Fact]
    public void Subject_tags_are_replaced_not_duplicated()
    {
        var tagged = EmailThreading.TagSubject("Re: Invoice mismatch [#1042]", "#1042");
        Assert.Equal("Re: Invoice mismatch [#1042]", tagged);
        Assert.Equal("Invoice mismatch", EmailThreading.StripReplyPrefixes(EmailThreading.StripTicketTag("RE: Fwd: Invoice mismatch [#1042]")));
        Assert.Null(InboundEmailProcessor.TagPrefix("#"));
        Assert.Equal("SD-", InboundEmailProcessor.TagPrefix("SD-"));
        Assert.Equal(77, EmailThreading.ExtractTicketNumber("Re: printer [SD-77]", "SD-"));
    }

    [Fact]
    public void Bounces_and_out_of_office_replies_are_detected()
    {
        var bounce = new MimeCodec().Parse(Raw("""
            From: Mail Delivery Subsystem <mailer-daemon@googlemail.com>
            To: support@wings.demo
            Subject: Delivery Status Notification (Failure)
            Message-ID: <bounce-1@google.com>
            MIME-Version: 1.0
            Content-Type: multipart/report; report-type=delivery-status; boundary="b1"

            --b1
            Content-Type: text/plain

            Address not found
            --b1
            Content-Type: message/delivery-status

            Reporting-MTA: dns; googlemail.com
            Final-Recipient: rfc822; nobody@example.com
            Action: failed
            Status: 5.1.1
            --b1--
            """));
        Assert.True(bounce.IsDeliveryReport);
        Assert.True(EmailThreading.IsAutoGenerated(bounce.Headers, "mailer-daemon@googlemail.com"));

        var ooo = new MimeCodec().Parse(Raw("""
            From: kavya@greenfieldfoods.demo
            To: support@wings.demo
            Subject: Automatic reply: Ticket received
            Auto-Submitted: auto-replied
            Message-ID: <ooo-1@greenfieldfoods.demo>
            Content-Type: text/plain

            I am out of office until Monday.
            """));
        Assert.True(EmailThreading.IsAutoGenerated(ooo.Headers, "kavya@greenfieldfoods.demo"));
    }
}
