using SupportDesk.Domain.Rules;

namespace SupportDesk.UnitTests.Domain;

public sealed class EmailThreadingTests
{
    [Fact]
    public void References_are_parsed_and_normalised()
    {
        var ids = EmailThreading.ParseReferences("<a1@x.com> <b2@y.com>\r\n <a1@x.com>");
        Assert.Equal(["a1@x.com", "b2@y.com"], ids);
        Assert.Equal("abc@host", EmailThreading.NormalizeMessageId(" <abc@host> "));
        Assert.Null(EmailThreading.NormalizeMessageId("<>"));
    }

    [Theory]
    [InlineData("Re: Invoice issue [#1042]", 1042L)]
    [InlineData("RE: [SD-77] Login problem", 77L)]
    [InlineData("Fwd: [Ticket #9] help", 9L)]
    [InlineData("No tag here", null)]
    public void Ticket_number_is_found_in_subject(string subject, long? expected) =>
        Assert.Equal(expected, EmailThreading.ExtractTicketNumber(subject));

    [Fact]
    public void Reply_prefixes_are_stripped_repeatedly() =>
        Assert.Equal("Invoice issue", EmailThreading.StripReplyPrefixes("RE: Fwd: AW: Re[2]: Invoice issue"));

    [Fact]
    public void Reply_token_round_trips_through_plus_address()
    {
        var address = EmailThreading.WithReplyToken("support@wings.demo", "ab12cd34ef");
        Assert.Equal("support+t-ab12cd34ef@wings.demo", address);
        Assert.Equal("ab12cd34ef", EmailThreading.ExtractReplyToken(["someone@else.com", address]));
    }

    [Fact]
    public void Auto_generated_mail_is_detected()
    {
        Assert.True(EmailThreading.IsAutoGenerated(new Dictionary<string, string> { ["Auto-Submitted"] = "auto-replied" }, "a@b.com"));
        Assert.True(EmailThreading.IsAutoGenerated(new Dictionary<string, string> { ["Precedence"] = "bulk" }, "a@b.com"));
        Assert.True(EmailThreading.IsAutoGenerated(new Dictionary<string, string>(), "MAILER-DAEMON@mx.example.com"));
        Assert.False(EmailThreading.IsAutoGenerated(new Dictionary<string, string> { ["Auto-Submitted"] = "no" }, "customer@abc.com"));
    }

    [Fact]
    public void Quoted_history_is_separated_from_the_new_reply()
    {
        var (reply, quoted) = EmailThreading.SplitQuotedText("Thanks, that fixed it.\n\nOn Mon, 12 Oct 2026 at 10:00, Support <support@wings.demo> wrote:\n> Please try again.");
        Assert.Equal("Thanks, that fixed it.", reply);
        Assert.StartsWith("On Mon", quoted);
        var (outlook, q2) = EmailThreading.SplitQuotedText("Still failing.\r\n-----Original Message-----\r\nFrom: Support");
        Assert.Equal("Still failing.", outlook);
        Assert.NotNull(q2);
    }

    [Theory]
    [InlineData("+91 98450 12345", "919845012345")]
    [InlineData("09845012345", "919845012345")]
    [InlineData("9845012345", "919845012345")]
    [InlineData("0044 20 7946 0958", "442079460958")]
    [InlineData("whatsapp:+14155550100", "14155550100")]
    public void Phones_are_normalised_for_matching(string input, string expected) =>
        Assert.Equal(expected, TextNormalization.NormalizePhone(input));

    [Fact]
    public void Text_helpers()
    {
        Assert.Equal("gst-invoice-mismatch", TextNormalization.Slugify("GST: Invoice  mismatch!"));
        Assert.Equal("ana@abc.com", TextNormalization.NormalizeEmail("  <Ana@ABC.com> "));
        Assert.Contains("invoice", TextNormalization.Tokenize("The invoices are wrong"));
        Assert.DoesNotContain("the", TextNormalization.Tokenize("The invoices are wrong"));
        Assert.Equal("Hello\nWorld", TextNormalization.HtmlToText("<p>Hello</p><p>World</p><script>x()</script>"));
        Assert.True(TextNormalization.Similarity("Ramesh Kumar", "Ramesh Kumaar") > 0.9);
    }
}
